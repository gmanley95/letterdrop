// Builds src/data/words.ts from the public-domain ENABLE word list (enable1.txt).
import { readFileSync, writeFileSync } from 'node:fs';

const MIN = 3;
const MAX = 10;
const words = readFileSync(new URL('../enable1.txt', import.meta.url), 'utf8')
  .split(/\r?\n/)
  .map((w) => w.trim().toUpperCase())
  .filter((w) => /^[A-Z]+$/.test(w) && w.length >= MIN && w.length <= MAX);

const body = `// AUTO-GENERATED by scripts/build-dictionary.mjs from ENABLE (public domain). Do not edit.
// ${words.length} words, ${MIN}-${MAX} letters.
export const WORDS = ${JSON.stringify(words.join('\n'))};
`;
writeFileSync(new URL('../src/data/words.ts', import.meta.url), body);
console.log(`Wrote ${words.length} words`);
